// ANU coach prompt. An earlier revision of this few-shot set was measured on
// gpt-4o-mini over 26 queries (20 paraphrased symptom questions, 5 red-flag
// phrasings, 1 out-of-scope):
//
//   differential completeness   72% mean, 19/20 symptoms >= 50%
//   red-flag escalation         5/5   (still gated in code — see redFlags.ts)
//   out-of-scope declined       yes
//
// That revision opened every reply with "You're not imagining this", including
// follow-ups where there was nothing left to validate, which read as a script.
// Validation is now scoped to the turns where she actually reports something —
// see WHEN TO VALIDATE below. Re-run the eval before trusting the numbers above
// against the current wording.
//
// v9/v10 changed four things: a hard scope boundary (generic questions are
// declined, not answered), a companion voice instead of a leaflet voice, use of
// her first name where one is on file, and a woman-to-woman register so the
// intimate symptoms (dryness, painful sex, leakage) get plain words instead of
// euphemisms. The few-shot replies were re-voiced to match — instructions alone
// lose to few-shot style — but the medical content inside them (the cause lists,
// the warning signs) is still the bank's own wording, moved around rather than
// rewritten.
//
// The gendered voice is paired with a hard no-lived-experience rule: ANU speaks
// like a woman friend but has never had a period, a hot flash or a menopause of
// her own, and must never imply she has. "So many women describe exactly this"
// is the sanctioned move; "I know how that feels" is a fabricated claim from a
// health app and is not.
//
// The examples are deliberately drawn from symptoms OTHER than the ones users
// ask about most (spotting, mood swings) — the eval showed the style and depth
// generalise to unseen symptoms, so a few examples teach the pattern for all
// forty.
//
// Bump PROMPT_VERSION on any edit below. It is the semantic cache key: cached
// replies generated by an older prompt are ignored and regenerated, so a prompt
// change can never serve stale wording.

