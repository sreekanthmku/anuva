export type ChatMessage = { role: 'system' | 'user' | 'assistant'; content: string };

/// How many prior exchanges to replay. Follow-up prompts ("Why does this
/// happen?") carry no symptom of their own, so without this the model answers
/// about whatever the few-shot examples primed it with. Two turns is enough to
/// resolve them and keeps input around 1.2k tokens.
export const HISTORY_TURNS = 2;

export type PriorTurn = { userMessage: string; reply: string; symptom: string | null };

/// Assistant turns are replayed as JSON so the model sees one consistent output
/// shape throughout — mixing prose examples with a JSON instruction makes it
/// drift back to prose.
function asAssistantContent(reply: string, symptom: string | null): string {
  return JSON.stringify({ reply, symptom });
}

/// Her profile name reaches the prompt as free text she typed herself, so it is
/// narrowed to something that can only be read as a name: the first word, no
/// newlines, no punctuation that could open a new instruction, and short. A name
/// that survives none of that is treated as no name at all.
export function sanitizeName(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const first = raw.trim().split(/\s+/)[0] ?? '';
  const cleaned = first.replace(/[^\p{L}\p{M}'’-]/gu, '').slice(0, 24);
  return cleaned.length >= 2 ? cleaned : null;
}

/// Appended to the system prompt rather than sent as its own message, so the
/// name is bound to the rules that govern how it may be used.
///
/// The worked examples are built here from her real name rather than written
/// into SYSTEM_PROMPT with a stand-in, so there is no example name anywhere in
/// the prompt for the model to copy into a reply.
function nameDirective(name: string | null): string {
  if (!name) {
    return '\n\nHER NAME: not given. Do not use a name in this conversation, and do not ask for one.';
  }
  return (
    `\n\nHER NAME: ${name}. Use "${name}", spelled exactly like that, the way a friend would — ` +
    `at most once in a reply and not in every reply. Address her with it ("That sounds exhausting, ${name}.") ` +
    `and never write it as a possessive or a subject ("${name}'s nights", "${name} should rest").`
  );
}

export function buildMessages(
  userMessage: string,
  history: PriorTurn[] = [],
  name: string | null = null,
): ChatMessage[] {
  const messages: ChatMessage[] = [
    { role: 'system', content: SYSTEM_PROMPT + nameDirective(sanitizeName(name)) },
  ];
  for (const shot of FEW_SHOT) {
    messages.push({ role: 'user', content: shot.user });
    messages.push({ role: 'assistant', content: asAssistantContent(shot.reply, shot.symptom) });
  }
  for (const turn of history.slice(-HISTORY_TURNS)) {
    messages.push({ role: 'user', content: turn.userMessage });
    // Replaying the symptom keeps a follow-up anchored to the same topic.
    messages.push({ role: 'assistant', content: asAssistantContent(turn.reply, turn.symptom) });
  }
  messages.push({ role: 'user', content: userMessage });
  return messages;
}
